def ed_text():
    out, lo = [], 0
    for hi, base, rate in EDT:
        rng = f"{man(hi)} 이하" if lo == 0 else (f"{man(lo)} 초과 {man(hi)} 이하" if hi else f"{man(lo)} 초과")
        out.append(f"{rng}: " + (f"총급여 × {rate}%" if base == 0 else f"{man(base)} + {man(lo)} 초과분 × {rate}%"))
        lo = hi or lo
    return "; ".join(out)


def earned_credit(tax):
    """근로소득세액공제(한도 제외): 130만 원 이하 55%, 초과분 30%."""
    return int(tax * 0.55) if tax <= 1300000 else int(715000 + (tax - 1300000) * 0.30)


